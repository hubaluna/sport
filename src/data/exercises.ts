export function exerciseHelpKey(name: string): string | null {
  const n = String(name || '').toLowerCase();
  const exact = Object.keys(EXERCISES).find((key) => EXERCISES[key].name.toLowerCase() === n);
  if (exact) return exact;
  if (n.includes('часткове підтягування')) return 'partialPull';
  if (n.includes('лопатки біля стіни')) return 'wallScap';
  if (n.includes('тяга резинки сидячи')) return 'seatedRow';
  if (n.includes('верхньої позиції')) return 'topHold';
  if (n.includes('одиночне строге') || n.includes('строгі підтягування')) return 'strictPull';
  if (n.includes('тяга резинки')) return 'bandPull';
  if (n.includes('сідничний міст')) return 'bridge';
  if (n.includes('передпліч')) return 'plank';
  if (n.includes('мертвий жук')) return 'deadBug';
  if (n.includes('колесо')) return 'wheel';
  if (n.includes('зворотні випади')) return 'lunge';
  if (n.includes('повільні віджим')) return 'slowPush';
  if (n.includes('негативн')) return 'negative';
  if (n.includes('лопаткові підтяг')) return 'scapPull';
  if (n.includes('активний вис')) return 'hang';
  if (n.includes('підтягування без резинки')) return 'strictPull';
  if (n.includes('підтягування з резинкою')) return 'assistedPull';
  if (n.includes('стрибки у планці')) return 'plankJump';
  if (n.includes('стрибки з присіду')) return 'squatJump';
  if (n.includes('прес:')) return 'abs';
  if (n.includes('віджим')) return 'push';
  if (n.includes('легка планка')) return 'highPlank';
  if (n.includes('присідання')) return 'squat';
  if (n.includes('нахили')) return 'hipHinge';
  if (n.includes('литка')) return 'calf';
  if (n.includes('грудні м’язи')) return 'chest';
  return null;
}
